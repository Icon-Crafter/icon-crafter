fn number(value: f64, precision: u32) -> String {
    let text = format!("{:.*}", precision as usize, value);
    let trimmed = text.trim_end_matches('0').trim_end_matches('.');
    if trimmed.is_empty() || trimmed == "-0" {
        "0".to_owned()
    } else {
        trimmed.to_owned()
    }
}

fn slug(input: &str) -> String {
    let mut out = String::new();
    for character in input.chars() {
        if character.is_ascii_alphanumeric() {
            out.push(character.to_ascii_lowercase());
        } else if !out.ends_with('-') && !out.is_empty() {
            out.push('-');
        }
    }
    let out = out.trim_matches('-');
    if out.is_empty() {
        "layer".to_owned()
    } else {
        out.to_owned()
    }
}

fn section_anchor(name: &str, index: usize) -> String {
    if index == 0 {
        slug(name)
    } else {
        format!("{}-{}", slug(name), index + 1)
    }
}

fn escape(input: &str) -> String {
    let mut out = String::with_capacity(input.len());
    for character in input.chars() {
        match character {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            _ => out.push(character),
        }
    }
    out
}

fn path_data(path: &VectorPath, precision: u32) -> String {
    let mut out = String::new();
    for contour in &path.contours {
        if contour.anchors.is_empty() {
            continue;
        }
        let first = &contour.anchors[0];
        let _ = write!(
            out,
            "M {} {} ",
            number(first.point.x, precision),
            number(first.point.y, precision)
        );
        let count = contour.anchors.len();
        let segments = if contour.closed {
            count
        } else {
            count.saturating_sub(1)
        };
        for index in 0..segments {
            let from = &contour.anchors[index];
            let to = &contour.anchors[(index + 1) % count];
            let _ = write!(
                out,
                "C {} {} {} {} {} {} ",
                number(from.out_handle.x, precision),
                number(from.out_handle.y, precision),
                number(to.in_handle.x, precision),
                number(to.in_handle.y, precision),
                number(to.point.x, precision),
                number(to.point.y, precision)
            );
        }
        if contour.closed {
            out.push('Z');
            out.push(' ');
        }
    }
    out.trim_end().to_owned()
}

/// Fills are exported from the first visible fill; utility used by callers that
/// need the same rule when building custom templates.
pub fn primary_fill_color(fills: &[Fill]) -> Option<Color> {
    fills
        .iter()
        .find(|fill| fill.visible)
        .and_then(|fill| match &fill.paint {
            dp_model::Paint::Solid { color } => Some(*color),
            _ => None,
        })
}

/// Bounding box of all roots of a page, in world space (used by callers that
/// want a page-sized wrapper).
pub fn page_content_bounds(page: &Page) -> Option<Rect> {
    let mut bounds: Option<Rect> = None;
    for root in &page.roots {
        let node = page.nodes.get(root)?;
        let rect = Rect::new(0.0, 0.0, node.transform.w, node.transform.h);
        bounds = Some(match bounds {
            Some(existing) => existing.union(rect),
            None => rect,
        });
    }
    bounds
}
