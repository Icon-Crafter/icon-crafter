//! Website export: a real HTML + CSS bundle generated from a design document.
//!
//! This is the engine side of the website-design workflow: frames become
//! `<section>`s, layers become absolutely positioned elements inside their
//! parent, text stays real text, vector geometry becomes inline SVG, and
//! prototype `navigate_to` links become anchor hot-spots so a design can be
//! explored as a static site.
//!
//! What this is *not*: a production website generator. Output is a visual
//! approximation (fixed pixel geometry, no responsive re-layout, no image
//! bytes, no server logic). Warnings in [`WebsiteExport::warnings`] list every
//! feature that needs manual work; the UI and docs must present it that way.

use std::fmt::Write as _;
use std::path::Path;

use dp_geom::{Mat2D, Point, Rect, VectorPath};
use dp_model::{Color, Document, Fill, Node, NodeId, NodeKind, Page, PageId};

use crate::ExportError;

/// Options for website export.
#[derive(Debug, Clone)]
pub struct WebsiteOptions {
    /// Document title used in `<title>` and the page header comment.
    pub title: String,
    /// Decimal places for CSS numbers.
    pub precision: u32,
    /// Export only these root nodes (frames); empty exports all roots.
    pub root_ids: Vec<NodeId>,
    /// Emit a `@media` block that scales sections down on narrow viewports.
    pub responsive_scale: bool,
    /// Include prototype `navigate_to` hot-spots as anchors.
    pub include_hotspots: bool,
}

impl Default for WebsiteOptions {
    fn default() -> Self {
        WebsiteOptions {
            title: "Icon Crafter website".to_owned(),
            precision: 2,
            root_ids: Vec::new(),
            responsive_scale: true,
            include_hotspots: true,
        }
    }
}

/// A generated website (index HTML + stylesheet) plus honest caveats.
#[derive(Debug, Clone, PartialEq)]
pub struct WebsiteExport {
    /// `index.html` contents.
    pub html: String,
    /// `styles.css` contents.
    pub css: String,
    /// Warnings about features that need manual work.
    pub warnings: Vec<String>,
    /// Number of `<section>` roots exported.
    pub sections: usize,
    /// Number of DOM elements exported.
    pub elements: usize,
}

/// Generates a website bundle for one page.
pub fn export_website(
    document: &Document,
    page_id: PageId,
    options: &WebsiteOptions,
) -> Result<WebsiteExport, ExportError> {
    let page = document
        .page(page_id)
        .ok_or(ExportError::MissingPage(page_id))?;
    let roots: Vec<NodeId> = if options.root_ids.is_empty() {
        page.roots.clone()
    } else {
        options.root_ids.clone()
    };
    let mut exporter = Exporter {
        page,
        precision: options.precision.clamp(0, 4),
        options,
        css: String::new(),
        body: String::new(),
        warnings: Vec::new(),
        elements: 0,
        sections: 0,
        ids: std::collections::HashMap::new(),
        warned: std::collections::HashSet::new(),
    };
    exporter.base_css();
    for (index, root) in roots.iter().enumerate() {
        exporter.section(*root, index)?;
    }
    if exporter.sections == 0 {
        return Err(ExportError::EmptyDocument);
    }
    let mut html = String::new();
    html.push_str("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n");
    html.push_str("<meta charset=\"utf-8\" />\n");
    html.push_str("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\" />\n");
    let _ = writeln!(html, "<title>{}</title>", escape(&options.title));
    html.push_str("<link rel=\"stylesheet\" href=\"styles.css\" />\n");
    html.push_str("</head>\n<body>\n");
    html.push_str(
        "<!-- Generated by Icon Crafter website export: fixed-pixel visual approximation. -->\n",
    );
    html.push_str(&exporter.body);
    html.push_str("</body>\n</html>\n");
    Ok(WebsiteExport {
        html,
        css: exporter.css,
        warnings: exporter.warnings,
        sections: exporter.sections,
        elements: exporter.elements,
    })
}

/// Writes `index.html` + `styles.css` into `directory` (created if needed).
pub fn write_website(
    document: &Document,
    page_id: PageId,
    options: &WebsiteOptions,
    directory: impl AsRef<Path>,
) -> Result<std::path::PathBuf, ExportError> {
    let bundle = export_website(document, page_id, options)?;
    let directory = directory.as_ref();
    std::fs::create_dir_all(directory)
        .map_err(|error| ExportError::Io(format!("create {}: {error}", directory.display())))?;
    let index = directory.join("index.html");
    std::fs::write(&index, &bundle.html)
        .map_err(|error| ExportError::Io(format!("write {}: {error}", index.display())))?;
    let css = directory.join("styles.css");
    std::fs::write(&css, &bundle.css)
        .map_err(|error| ExportError::Io(format!("write {}: {error}", css.display())))?;
    Ok(index)
}

struct Exporter<'a> {
    page: &'a Page,
    precision: u32,
    options: &'a WebsiteOptions,
    css: String,
    body: String,
    warnings: Vec<String>,
    elements: usize,
    sections: usize,
    ids: std::collections::HashMap<NodeId, String>,
    warned: std::collections::HashSet<&'static str>,
}

impl Exporter<'_> {
    fn base_css(&mut self) {
        self.css
            .push_str("/* Generated by Icon Crafter website export. */\n");
        self.css
            .push_str("* { box-sizing: border-box; }\nhtml, body { margin: 0; padding: 0; }\n");
        self.css.push_str("body { background: #101318; }\n");
        self.css.push_str(
            ".ic-section { position: relative; margin: 0 auto 24px; overflow: hidden; }\n",
        );
        self.css
            .push_str(".ic-node { position: absolute; }\n.ic-text { white-space: pre-wrap; }\n");
        self.css.push_str(
            ".ic-hotspot { position: absolute; display: block; background: transparent; border: 1px solid rgba(79,209,197,.6); border-radius: 4px; text-decoration: none; }\n",
        );
        self.css
            .push_str(".ic-image { display: block; object-fit: contain; background: rgba(255,255,255,.06); }\n");
        if self.options.responsive_scale {
            self.css
                .push_str("@media (max-width: 900px) { .ic-section { max-width: 100%; } }\n");
        }
    }

    fn section(&mut self, root_id: NodeId, index: usize) -> Result<(), ExportError> {
        let Some(root) = self.page.nodes.get(&root_id).cloned() else {
            return Ok(());
        };
        let class = self.node_class(&root, index);
        let frame_like = matches!(
            root.kind,
            NodeKind::Frame
                | NodeKind::Component
                | NodeKind::ComponentSet
                | NodeKind::Group
                | NodeKind::Instance
        );
        if !frame_like {
            self.warn(
                "root",
                "top-level layers that are not frames are placed in a zero-gap section wrapper",
            );
        }
        let w = number(root.transform.w.max(1.0), self.precision);
        let h = number(root.transform.h.max(1.0), self.precision);
        let background = self.background_css(&root);
        let tag = if frame_like { "section" } else { "div" };
        let id = section_anchor(&self.node_name(&root), index);
        let _ = writeln!(
            self.body,
            "<{tag} id=\"{id}\" class=\"ic-section {class}\" aria-label=\"{}\">",
            escape(&self.node_name(&root))
        );
        let box_extra = self.box_extra_css(&root);
        if let Some(bg) = background {
            let _ = writeln!(
                self.css,
                ".{class} {{ width: {w}px; height: {h}px; background: {bg}; {box_extra} }}"
            );
        } else {
            let _ = writeln!(
                self.css,
                ".{class} {{ width: {w}px; height: {h}px; {box_extra} }}"
            );
        }
        self.sections += 1;
        self.elements += 1;
        // Children are positioned in root-local coordinates.
        let child_ids: Vec<NodeId> = root.children.clone();
        for child in child_ids {
            self.element(child, root_id, 1);
        }
        if self.options.include_hotspots {
            self.hotspots(root_id)?;
        }
        let _ = writeln!(self.body, "</{tag}>");
        Ok(())
    }

    fn element(&mut self, id: NodeId, root: NodeId, depth: usize) {
        if depth > 256 {
            return;
        }
        let Some(node) = self.page.nodes.get(&id).cloned() else {
            return;
        };
        let class = self.node_class(&node, self.elements);
        let visible = node.visible;
        if !visible {
            return;
        }
        // Position relative to the exported section root.
        let world = self.world_matrix(id);
        let root_matrix = self.world_matrix(root);
        let Some(local) = relative_matrix(world, root_matrix) else {
            self.warn(
                "matrix",
                "a layer has a non-invertible transform chain and was skipped",
            );
            return;
        };
        let position = local.apply_point(Point::new(0.0, 0.0));
        let w = node.transform.w.max(0.0);
        let h = node.transform.h.max(0.0);
        let rotation = normalized_rotation(local);
        let mut style = format!(
            "left: {}px; top: {}px; width: {}px; height: {}px;",
            number(position.x, self.precision),
            number(position.y, self.precision),
            number(w, self.precision),
            number(h, self.precision)
        );
        if rotation.abs() > 0.01 {
            let _ = write!(
                style,
                " transform: rotate({}deg);",
                number(rotation, self.precision)
            );
        }
        if node.opacity < 0.999 {
            let _ = write!(style, " opacity: {};", number(node.opacity, 3));
        }
        if node.blend != dp_model::BlendMode::Normal {
            let _ = write!(style, " mix-blend-mode: {};", blend_css(node.blend));
            self.warn(
                "blend",
                "CSS mix-blend-mode approximates design blend modes",
            );
        }
        let fill = self.fill_css(&node);
        let mut extra = String::new();
        match node.kind {
            NodeKind::Text => {
                if let Some(text) = &node.text {
                    let _ = writeln!(
                        self.body,
                        "<div class=\"ic-node ic-text {class}\" style=\"{style}{}\" aria-label=\"{}\">",
                        self.typography_css(&node),
                        escape(&self.node_name(&node))
                    );
                    let content = if text.characters.is_empty() {
                        "".to_owned()
                    } else {
                        escape(&text.characters)
                    };
                    let _ = writeln!(self.body, "{content}</div>");
                    self.elements += 1;
                }
            }
            NodeKind::Vector | NodeKind::Polygon | NodeKind::Star => {
                if let Some(svg) = self.shape_svg(&node, w, h) {
                    let _ = writeln!(
                        self.body,
                        "<div class=\"ic-node {class}\" style=\"{style}\" aria-label=\"{}\">{svg}</div>",
                        escape(&self.node_name(&node))
                    );
                    self.elements += 1;
                }
            }
            NodeKind::Image => {
                let _ = writeln!(
                    self.body,
                    "<img class=\"ic-node ic-image {class}\" style=\"{style}\" alt=\"{}\" />",
                    escape(&self.node_name(&node))
                );
                self.elements += 1;
                self.warn(
                    "images",
                    "image layers are exported as empty <img> placeholders; copy asset files into the export directory and set src",
                );
            }
            NodeKind::Ellipse => {
                extra.push_str(" border-radius: 50%;");
                if let Some(bg) = &fill {
                    extra.push_str(&format!(" background: {bg};"));
                }
                let _ = writeln!(
                    self.body,
                    "<div class=\"ic-node {class}\" style=\"{style}{extra}\" aria-label=\"{}\"></div>",
                    escape(&self.node_name(&node))
                );
                self.elements += 1;
            }
            NodeKind::Boolean => {
                self.warn(
                    "boolean",
                    "boolean layers are exported as empty boxes; export them as SVG for real geometry",
                );
                if let Some(bg) = &fill {
                    extra.push_str(&format!(" background: {bg};"));
                }
                let _ = writeln!(
                    self.body,
                    "<div class=\"ic-node {class}\" style=\"{style}{extra}\"></div>"
                );
                self.elements += 1;
            }
            NodeKind::Line | NodeKind::Connector => {
                let _ = writeln!(
                    self.body,
                    "<div class=\"ic-node {class}\" style=\"{style}\"></div>"
                );
                self.elements += 1;
                self.warn("lines", "lines/connectors are exported as empty boxes");
            }
            NodeKind::Sticky => {
                let bg = self.fill_css(&node).unwrap_or_else(|| "#f2b84b".to_owned());
                let _ = writeln!(
                    self.body,
                    "<div class=\"ic-node {class}\" style=\"{style} background: {bg}; border-radius: 6px; padding: 8px;\">"
                );
                if let Some(text) = &node.text {
                    let _ = writeln!(
                        self.body,
                        "<div class=\"ic-text\">{}</div>",
                        escape(&text.characters)
                    );
                }
                let _ = writeln!(self.body, "</div>");
                self.elements += 1;
            }
            NodeKind::Slice => {}
            _ => {
                if let Some(bg) = &fill {
                    extra.push_str(&format!(" background: {bg};"));
                }
                extra.push_str(&self.border_css(&node));
                extra.push_str(&self.radius_css(&node));
                extra.push_str(&self.shadow_css(&node));
                let _ = writeln!(
                    self.body,
                    "<div class=\"ic-node {class}\" style=\"{style}{extra}\" aria-label=\"{}\"></div>",
                    escape(&self.node_name(&node))
                );
                self.elements += 1;
            }
        }
        // Layers are emitted as flat siblings: absolute CSS coordinates are then
        // relative to the section root instead of stacking nested offsets.
        for child in node.children.clone() {
            self.element(child, root, depth + 1);
        }
    }

    fn hotspots(&mut self, root: NodeId) -> Result<(), ExportError> {
        let mut ids = Vec::new();
        self.collect(root, &mut ids);
        let root_world = self.world_matrix(root);
        for id in ids {
            let Some(node) = self.page.nodes.get(&id) else {
                continue;
            };
            let Some(prototype) = &node.prototype else {
                continue;
            };
            for interaction in &prototype.interactions {
                if !matches!(
                    interaction.trigger,
                    dp_model::prototype::Trigger::Click { .. }
                ) {
                    continue;
                }
                for action in &interaction.actions {
                    let dp_model::prototype::Action::NavigateTo { frame_id, .. } = action else {
                        continue;
                    };
                    let Some(world) = self.world_matrix(id) else {
                        continue;
                    };
                    let Some(local) = relative_matrix(Some(world), root_world) else {
                        continue;
                    };
                    let position = local.apply_point(Point::new(0.0, 0.0));
                    let target_name = self
                        .page
                        .nodes
                        .get(frame_id)
                        .map(|node| self.node_name(node))
                        .unwrap_or_else(|| "target".to_owned());
                    let anchor = section_anchor(&target_name, 0);
                    let label = self.node_name(node);
                    let _ = writeln!(
                        self.body,
                        "<a class=\"ic-hotspot\" href=\"#{anchor}\" aria-label=\"Go to {}\" title=\"{}\" style=\"left: {}px; top: {}px; width: {}px; height: {}px;\"></a>",
                        escape(&target_name),
                        escape(&label),
                        number(position.x, self.precision),
                        number(position.y, self.precision),
                        number(node.transform.w.max(0.0), self.precision),
                        number(node.transform.h.max(0.0), self.precision)
                    );
                    self.elements += 1;
                }
            }
        }
        Ok(())
    }

    fn collect(&self, id: NodeId, out: &mut Vec<NodeId>) {
        out.push(id);
        if let Some(node) = self.page.nodes.get(&id) {
            for child in &node.children {
                self.collect(*child, out);
            }
        }
    }

    fn warn(&mut self, kind: &'static str, message: &str) {
        if self.warned.insert(kind) {
            self.warnings.push(message.to_owned());
        }
    }

    fn node_name(&self, node: &Node) -> String {
        if node.name.is_empty() {
            format!("Layer {:?}", node.kind).to_lowercase()
        } else {
            node.name.clone()
        }
    }

    fn node_class(&mut self, node: &Node, index: usize) -> String {
        if let Some(existing) = self.ids.get(&node.id) {
            return existing.clone();
        }
        let base = slug(&self.node_name(node));
        let class = format!("ic-{base}-{index}");
        self.ids.insert(node.id, class.clone());
        let _ = writeln!(
            self.css,
            ".{class} {{ /* {} ({:?}) */ }}",
            slug(&self.node_name(node)),
            node.kind
        );
        class
    }

    fn world_matrix(&self, id: NodeId) -> Option<Mat2D> {
        let node = self.page.nodes.get(&id)?;
        let mut matrix = node.transform.matrix();
        let mut parent = node.parent;
        let mut guard = 0;
        while let Some(parent_id) = parent {
            guard += 1;
            if guard > 256 {
                return None;
            }
            let parent_node = self.page.nodes.get(&parent_id)?;
            matrix = parent_node.transform.matrix().mul(matrix);
            parent = parent_node.parent;
        }
        Some(matrix)
    }

    fn fill_css(&self, node: &Node) -> Option<String> {
        let fill = node.style.fills.iter().find(|fill| fill.visible)?;
        paint_css(&fill.paint, fill.opacity)
    }

    fn background_css(&mut self, node: &Node) -> Option<String> {
        let value = self.fill_css(node);
        if value.is_none() && !node.style.fills.is_empty() {
            self.warn(
                "hidden-fills",
                "hidden fills are skipped during website export",
            );
        }
        value
    }

    fn border_css(&self, node: &Node) -> String {
        let Some(stroke) = node.style.strokes.iter().find(|stroke| stroke.visible) else {
            return String::new();
        };
        let Some(color) = paint_css(&stroke.paint, stroke.opacity) else {
            return String::new();
        };
        format!(
            " border: {}px solid {};",
            number(stroke.weight, self.precision),
            color
        )
    }

    fn radius_css(&self, node: &Node) -> String {
        let radii = node.style.corner_radii;
        if [radii.tl, radii.tr, radii.br, radii.bl]
            .iter()
            .all(|radius| *radius <= 0.0)
        {
            return String::new();
        }
        format!(
            " border-radius: {}px {}px {}px {}px;",
            number(radii.tl, self.precision),
            number(radii.tr, self.precision),
            number(radii.br, self.precision),
            number(radii.bl, self.precision)
        )
    }

    fn shadow_css(&mut self, node: &Node) -> String {
        let mut out = String::new();
        let mut shadows = Vec::new();
        for effect in &node.style.effects {
            match effect {
                dp_model::Effect::DropShadow {
                    color,
                    offset,
                    blur,
                    spread,
                    ..
                } => shadows.push(format!(
                    "{}px {}px {}px {}px {}",
                    number(offset.x, self.precision),
                    number(offset.y, self.precision),
                    number(*blur, self.precision),
                    number(*spread, self.precision),
                    css_color(*color)
                )),
                _ => self.warn(
                    "effects",
                    "inner shadows and blur effects are not exported to CSS",
                ),
            }
        }
        if !shadows.is_empty() {
            let _ = write!(out, " box-shadow: {};", shadows.join(", "));
        }
        out
    }

    fn box_extra_css(&mut self, node: &Node) -> String {
        let mut out = String::new();
        out.push_str(&self.radius_css(node));
        out.push_str(&self.border_css(node));
        out.push_str(&self.shadow_css(node));
        out
    }

    fn typography_css(&self, node: &Node) -> String {
        let Some(text) = &node.text else {
            return String::new();
        };
        let style = &text.style;
        let mut out = format!(
            " font-family: \"{}\"; font-size: {}px; font-weight: {}; line-height: {}px;",
            style.font_family.replace('"', "'"),
            number(style.font_size, self.precision),
            style.font_weight,
            number(
                style
                    .line_height
                    .resolve(style.font_size)
                    .unwrap_or(style.font_size * 1.2),
                self.precision
            )
        );
        if style.italic {
            out.push_str(" font-style: italic;");
        }
        if style.letter_spacing.abs() > 0.001 {
            let _ = write!(
                out,
                " letter-spacing: {}px;",
                number(style.letter_spacing, self.precision)
            );
        }
        let align = match text.paragraph.align {
            dp_model::TextAlign::Left => "left",
            dp_model::TextAlign::Center => "center",
            dp_model::TextAlign::Right => "right",
            dp_model::TextAlign::Justified => "justify",
        };
        let _ = write!(out, " text-align: {align};");
        if let Some(color) = style
            .fills
            .iter()
            .find(|fill| fill.visible)
            .and_then(|fill| paint_css(&fill.paint, fill.opacity))
        {
            let _ = write!(out, " color: {color};");
        }
        out
    }

    fn shape_svg(&mut self, node: &Node, w: f64, h: f64) -> Option<String> {
        let path = match &node.geometry {
            Some(dp_model::NodeGeometry::Vector { path }) => path.clone(),
            Some(dp_model::NodeGeometry::Polygon { point_count }) => {
                dp_geom::shapes::polygon_path(dp_geom::Size::new(w, h), *point_count)
            }
            Some(dp_model::NodeGeometry::Star {
                point_count,
                inner_ratio,
            }) => dp_geom::shapes::star_path(dp_geom::Size::new(w, h), *point_count, *inner_ratio),
            _ => {
                self.warn(
                    "vectors",
                    "vector layers without explicit geometry are skipped in website export",
                );
                return None;
            }
        };
        let data = path_data(&path, self.precision);
        if data.is_empty() {
            return None;
        }
        let fill = self.fill_css(node).unwrap_or_else(|| "none".to_owned());
        let stroke = self.border_css(node);
        let stroke_attr = if stroke.is_empty() {
            String::new()
        } else {
            let color = self
                .fill_css(&stroke_only_node(node))
                .unwrap_or_else(|| "none".to_owned());
            let weight = node
                .style
                .strokes
                .iter()
                .find(|stroke| stroke.visible)
                .map(|stroke| stroke.weight)
                .unwrap_or(1.0);
            format!(
                " stroke=\"{color}\" stroke-width=\"{}\"",
                number(weight, self.precision)
            )
        };
        Some(format!(
            "<svg width=\"100%\" height=\"100%\" viewBox=\"0 0 {} {}\" fill=\"none\" xmlns=\"http://www.w3.org/2000/svg\" aria-hidden=\"true\"><path d=\"{data}\" fill=\"{fill}\"{stroke_attr} fill-rule=\"nonzero\"/></svg>",
            number(w.max(1.0), self.precision),
            number(h.max(1.0), self.precision)
        ))
    }
}

fn stroke_only_node(node: &Node) -> Node {
    let mut clone = node.clone();
    clone.style.fills.clear();
    clone.style.effects.clear();
    clone.style.strokes.truncate(1);
    clone
}

fn relative_matrix(world: Option<Mat2D>, root: Option<Mat2D>) -> Option<Mat2D> {
    let world = world?;
    let root = root?;
    let inverse = root.inverse()?;
    Some(inverse.mul(world))
}

fn normalized_rotation(matrix: Mat2D) -> f64 {
    let radians = matrix.m12.atan2(matrix.m11);
    let degrees = radians.to_degrees();
    (degrees * 100.0).round() / 100.0
}

fn paint_css(paint: &dp_model::Paint, opacity: f64) -> Option<String> {
    match paint {
        dp_model::Paint::Solid { color } => Some(css_color(Color {
            a: color.a * opacity,
            ..*color
        })),
        dp_model::Paint::Linear { stops, .. } => {
            Some(gradient_css("linear-gradient(180deg", stops, opacity))
        }
        dp_model::Paint::Radial { stops, .. } => {
            Some(gradient_css("radial-gradient(circle", stops, opacity))
        }
        _ => None,
    }
}

fn gradient_css(function: &str, stops: &[dp_model::GradientStop], opacity: f64) -> String {
    let body: Vec<String> = stops
        .iter()
        .map(|stop| {
            format!(
                "{} {}%",
                css_color(Color {
                    a: stop.color.a * opacity,
                    ..stop.color
                }),
                number(stop.position * 100.0, 1)
            )
        })
        .collect();
    format!("{function}, {})", body.join(", "))
}

fn css_color(color: Color) -> String {
    if color.a >= 0.999 {
        color.to_hex()
    } else {
        format!(
            "rgba({}, {}, {}, {})",
            (color.r.clamp(0.0, 1.0) * 255.0).round() as u8,
            (color.g.clamp(0.0, 1.0) * 255.0).round() as u8,
            (color.b.clamp(0.0, 1.0) * 255.0).round() as u8,
            number(color.a, 3)
        )
    }
}

